    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        String nombre = txtNombreRepartidor.getText().trim();

        if (nombre.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "El nombre del repartidor no puede estar vacio.",
                    "Advertencia",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        dao.RepartidorDAO repartidorDAO = new dao.RepartidorDAO();

        model.Repartidor nuevoRepartidor = new model.Repartidor();
        nuevoRepartidor.setNombre(nombre);

        repartidorDAO.guardar(nuevoRepartidor);

        cargarTablaRepartidores();
        txtNombreRepartidor.setText("");
        javax.swing.JOptionPane.showMessageDialog(this, "Repartidor registrado con exito.");
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        if (idRepartidorSeleccionado == -1) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Por favor, seleccione un repartidor de la tabla para editar.",
                    "Advertencia",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        String nuevoNombre = txtNombreRepartidor.getText().trim();
        if (nuevoNombre.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "El nombre no puede estar vacio.",
                    "Advertencia",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        dao.RepartidorDAO repartidorDAO = new dao.RepartidorDAO();
        repartidorDAO.actualizarRegistro(idRepartidorSeleccionado, nuevoNombre);

        cargarTablaRepartidores();
        javax.swing.JOptionPane.showMessageDialog(this, "Repartidor actualizado con exito.");
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (idRepartidorSeleccionado == -1) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Por favor, seleccione un repartidor de la tabla para eliminar.",
                    "Advertencia",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        int confirmacion = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "¿Esta seguro de eliminar al repartidor seleccionado?",
                "Confirmar Eliminacion",
                javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (confirmacion == javax.swing.JOptionPane.YES_OPTION) {
            dao.RepartidorDAO repartidorDAO = new dao.RepartidorDAO();
            repartidorDAO.eliminarRegistro(idRepartidorSeleccionado);

            cargarTablaRepartidores();
            javax.swing.JOptionPane.showMessageDialog(this, "Repartidor eliminado con exito.");
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

