    private void configurarTablaYEventos() {
        cargarTablaRepartidores();

        tblRepartidores.getSelectionModel().addListSelectionListener(event -> {
            if (!event.getValueIsAdjusting() && tblRepartidores.getSelectedRow() != -1) {
                int fila = tblRepartidores.getSelectedRow();

                idRepartidorSeleccionado = Integer.parseInt(tblRepartidores.getValueAt(fila, 0).toString());
                String nombre = tblRepartidores.getValueAt(fila, 1).toString();

                txtNombreRepartidor.setText(nombre);
            }
        });
    }

    private void cargarTablaRepartidores() {
        dao.RepartidorDAO repartidorDAO = new dao.RepartidorDAO();
        java.util.List<model.Repartidor> lista = repartidorDAO.listarTodos();

        javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel(
                new Object[]{"ID", "Nombre"}, 0
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        for (model.Repartidor r : lista) {
            modelo.addRow(new Object[]{r.getId(), r.getNombre()});
        }

        tblRepartidores.setModel(modelo);

        idRepartidorSeleccionado = -1;
        txtNombreRepartidor.setText("");
    }

